const SERIES = {};
SERIES_DATA.forEach(s => {
    SERIES[s.id] = s.photos.map(p => ({ src: p.src, alt: p.alt, caption: p.caption }));
});

const lightbox = document.getElementById('lightbox');
const lbImg    = document.getElementById('lbImg');
const lbCap    = document.getElementById('lbCaption');
const lbCount  = document.getElementById('lbCounter');
let currentSeries = null, currentIndex = 0;

function openLightbox(series, index) {
    currentSeries = series;
    currentIndex  = index;
    showLbPhoto();
    lightbox.classList.add('open');
    document.body.style.overflow = 'hidden';
}
function closeLightbox() {
    lightbox.classList.remove('open');
    document.body.style.overflow = '';
}
function showLbPhoto() {
    const photos = SERIES[currentSeries];
    const p = photos[currentIndex];
    lbImg.src = p.src;
    lbImg.alt = p.alt;
    lbCap.textContent = p.caption;
    lbCount.textContent = (currentIndex + 1) + ' / ' + photos.length;
}
function lbNav(dir) {
    const len = SERIES[currentSeries].length;
    currentIndex = (currentIndex + dir + len) % len;
    showLbPhoto();
}

document.querySelectorAll('.photo-item').forEach(item => {
    item.addEventListener('click', () => {
        if (!item.closest('.photo-strip').classList.contains('dragging')) {
            openLightbox(item.dataset.series, parseInt(item.dataset.index));
        }
    });
});
document.getElementById('lbClose').addEventListener('click', closeLightbox);
document.getElementById('lbPrev').addEventListener('click', () => lbNav(-1));
document.getElementById('lbNext').addEventListener('click', () => lbNav(1));
lightbox.addEventListener('click', e => { if (e.target === lightbox) closeLightbox(); });
if (window.__photoKeyAbort) window.__photoKeyAbort.abort();
window.__photoKeyAbort = new AbortController();
document.addEventListener('keydown', e => {
    if (!lightbox.classList.contains('open')) return;
    if (e.key === 'Escape') closeLightbox();
    if (e.key === 'ArrowLeft') lbNav(-1);
    if (e.key === 'ArrowRight') lbNav(1);
}, { signal: window.__photoKeyAbort.signal });
