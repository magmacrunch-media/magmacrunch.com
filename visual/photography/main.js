const container = document.getElementById('series-container');

function renderArchiveLink(href, text) {
    return '<a href="' + href + '" style="color:var(--dim);text-decoration:none;border-bottom:1px solid var(--dim);transition:color 0.15s,border-color 0.15s;" onmouseover="this.style.color=\'var(--mintteal)\';this.style.borderColor=\'var(--mintteal)\'" onmouseout="this.style.color=\'var(--dim)\';this.style.borderColor=\'var(--dim)\'">' + text + '</a>';
}

SERIES_DATA.forEach((s, si) => {
    const el = document.createElement('div');
    el.className = 'series';
    el.id = 'series-' + s.id;
    if (s.noAnimation) el.style.cssText = 'animation:none!important;opacity:1!important;';

    let metaHTML = s.meta;
    if (s.metaLink) metaHTML += renderArchiveLink(s.metaLink.href, s.metaLink.text);

    let html = '<div class="series-header">' +
        '<span class="series-title">' + s.title + '</span>' +
        '<span class="series-meta">' + metaHTML + '</span>' +
        '</div>';

    if (s.desc) html += '<p class="series-desc">' + s.desc + '</p>';

    html += '<div class="photo-strip-wrap">' +
        '<div class="photo-strip">';

    s.photos.forEach((p, i) => {
        const cls = p.aspect || 'landscape';
        html += '<div class="photo-item ' + cls + '" data-series="' + s.id + '" data-index="' + i + '">' +
            '<img src="' + p.src + '" alt="' + p.alt + '" loading="lazy">' +
            '<div class="photo-caption">' + p.caption + '</div>' +
            '</div>';
    });

    html += '</div><div class="strip-scroll-hint">scroll → </div></div>';
    el.innerHTML = html;
    container.appendChild(el);

    if (s.divider !== false) {
        const divider = document.createElement('div');
        divider.className = 'section-divider';
        container.appendChild(divider);
    }
});

/* ══════════════════════════════════════════════════
   DRAG TO SCROLL
   ══════════════════════════════════════════════════ */
document.querySelectorAll('.photo-strip').forEach(strip => {
    let isDown = false, startX, scrollLeft;
    strip.addEventListener('mousedown', e => {
        isDown = true; strip.classList.add('dragging');
        startX = e.pageX - strip.offsetLeft;
        scrollLeft = strip.scrollLeft;
    });
    strip.addEventListener('mouseleave', () => { isDown = false; strip.classList.remove('dragging'); });
    strip.addEventListener('mouseup', () => { isDown = false; strip.classList.remove('dragging'); });
    strip.addEventListener('mousemove', e => {
        if (!isDown) return;
        e.preventDefault();
        const x = e.pageX - strip.offsetLeft;
        strip.scrollLeft = scrollLeft - (x - startX) * 1.2;
    });
    const wrap = strip.closest('.photo-strip-wrap');
    strip.addEventListener('scroll', () => { if (strip.scrollLeft > 30) wrap.classList.add('scrolled'); }, { passive: true });
});

